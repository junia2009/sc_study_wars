// 判断シーン。端末(地図の T)の前を通ると、ゲームが止まってこの画面が出る。
//
//   from     'sato' = 佐藤さんからの相談 / 'self' = 自分あてのメール
//   ask      相談のひとこと
//   time     考えられる秒数。0 なら制限なし(急かしてくるメールのときだけ付ける)
//   mock     本物そっくりのメール。プレイヤーは、怪しいと思うところをタップして印を付ける
//              {{ }} = 本当に怪しいところ(見抜くと加点。見落とすと答え合わせで黄色)
//              [[ ]] = 印を付けられるが問題ないところ(印を付けると「疑いすぎ」で業務の遅れ +3%)
//              印を付けられるところは「引っかけ」も混ぜる(全部に印を付けても得しないように)。
//              引っかけは、本物と見比べて一致するもの(表示名・台帳と同じ部分)や、ただのあいさつに限る。
//              口実や話題そのもの(「監査の都合で」など)は、怪しいと感じて当然なので引っかけにしない
//   inspect  「詳しく調べる」で分かること(なければ null)
//   clues    見比べに使う手がかり(手帳で開ける)
//   choices  選択肢
//     needs   この手がかりを持っているときだけ選べる。持っていないときは alt に差し替わる
//     tier    best 最善 / safe 安全だが遅い / ok 無事(たまたま) / close 惜しい / fooled 引っかかった
//     leak    漏洩リスクが増える量(%) / delay 業務の遅れが増える量(%) / cause 報告書に書かれる原因
//     rule    どの基本動作で解けるか(1 見る / 2 別の道で確かめる / 3 迷ったら相談)
//
// 社名・人名・ドメインはすべて架空。ドメインは例示用の .example を使う。

